/**
 * ============================================================================
 *  外部の方向け 観覧抽選フォームの設定 — ここだけ書き換えてください
 * ============================================================================
 *
 * このファイルは /lottery-external ページ（外部の方向けの案内ページ）が読む
 * 唯一の設定です。ページ本体（page.tsx）を触らなくても、フォームのURLと
 * 受付期間の表記をここで差し替えられます。
 *
 * 校内の生徒・保護者・教職員が使う抽選は、このページとは別物です
 * （/lottery = ログインが必要な校内向け申込ページ、定義は lib/lotteries.ts）。
 * こちらは外部業者のフォーム（2025年は LoGoフォーム）へ誘導するだけの
 * 静的な案内ページで、DBにも触れません。
 */

/**
 * 申込フォームのURL。
 *
 * まだURLが決まっていない場合は null のままにしてください。
 * null の間はページにボタンが出ず、「準備中」の案内が表示されます。
 * URL が入ると「申し込みフォームへ」ボタンが出ます。
 *
 * 例: export const EXTERNAL_FORM_URL = "https://logoform.jp/form/XXXX/XXXXXX";
 */
export const EXTERNAL_FORM_URL: string | null = null;

/**
 * 受付期間の表示用テキスト。フォーム側の設定と必ず一致させてください
 * （このページは表示するだけで、締切を機械的に判定はしません）。
 *
 * 期間が未定のうちは null にすると「後日お知らせします」と表示されます。
 * 例: "8月22日（土）12:00 ～ 9月5日（土）18:00"
 */
export const APPLICATION_PERIOD: string | null = null;

/**
 * 当選発表の予定時期。未定なら null。
 * 例: "9月8日（火）頃"
 */
export const RESULT_ANNOUNCEMENT: string | null = null;

/**
 * 当選者一覧ページのURL（抽選後に公開する場合）。
 * 未公開のうちは null にしておくと、当選発表の節にリンクが出ません。
 * 例: "/lottery-external/results" や外部URL。
 */
export const RESULT_PAGE_URL: string | null = null;

/**
 * ページ上部に出すお知らせ（追記）。新しいものを先頭に足してください。
 * date はそのまま表示されるので「2026/09/09」のような表記で構いません。
 * 空配列のときはお知らせ欄自体が表示されません。
 *
 * 例:
 *   { date: "2026/09/09", body: "当日抽選は実施しません。" },
 */
export const NOTICES: readonly { date: string; body: string }[] = [];
