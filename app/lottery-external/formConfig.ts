/**
 * 申込フォームのURL。
 *
 * まだURLが決まっていない場合は null のままにしてください。
 * null の間はページにボタンが出ず、「準備中」の案内が表示されます。
 * URL が入ると「申し込みフォームへ」ボタンが出ます。
 *
 * 例: export const EXTERNAL_FORM_URL = "https://logoform.jp/form/XXXX/XXXXXX";
 */
export const EXTERNAL_FORM_URL: string | null =
  "https://logoform.jp/form/tmgform/1691356";

/**
 * 「申し込みフォームへ」ボタンを実際に表示する期間。
 *
 * サーバー側の現在時刻で判定します（<TimeGuard> に渡します）。
 * この期間の外では、ボタンの代わりに「受付期間外」の案内が出ます。
 * null にすると、その側の判定を行いません
 * （FORM_OPEN_AT が null なら公開当初から、FORM_CLOSE_AT が null なら無期限に表示）。
 *
 * ★必ず「+09:00」まで書いてください。省略するとサーバーのタイムゾーン
 *   （本番は UTC）で解釈され、9時間ずれます。
 *
 * 上の APPLICATION_PERIOD（表示用テキスト）と必ず一致させてください。
 * FORM_CLOSE_AT は「その時刻まで表示」です。「8月25日 終日」なら
 * 翌26日の 00:00:00 を指定します。
 */
export const FORM_OPEN_AT: string | null = "2026-08-10T17:30:00+09:00";
export const FORM_CLOSE_AT: string | null = "2026-08-26T00:00:00+09:00";

/**
 * 受付期間の表示用テキスト。フォーム側の設定と必ず一致させてください
 * （ここはあくまで表示用の文字列です。ボタンを出す・引っ込める判定は
 * 下の FORM_OPEN_AT / FORM_CLOSE_AT が行うので、両方を揃えてください）。
 *
 * 期間が未定のうちは null にすると「後日お知らせします」と表示されます。
 * 例: "8月22日（土）12:00 ～ 9月5日（土）18:00"
 */
export const APPLICATION_PERIOD: string | null =
  "8月17日（月）12時〜8月25日（火）終日";

/**
 * 当選発表の予定時期。未定なら null。
 * 例: "9月8日（火）頃"
 */
export const RESULT_ANNOUNCEMENT: string | null = "8月27日（木）以降";

/**
 * 当選者一覧ページのURL（抽選後に公開する場合）。
 * 未公開のうちは null にしておくと、当選発表の節にリンクが出ません。
 * 例: "/lottery-external/results" や外部URL。
 */
export const RESULT_PAGE_URL: string | null = null;

/**
 * ページ上部に出すお知らせ（追記）。新しいものを先頭に足してください。
 * date はそのまま表示されるので「2026/09/09」のような表記で構いません。
 * 空配列のときはお知らせ欄自体が表示されません。
 *
 * 例:
 *   { date: "2026/09/09", body: "当日抽選は実施しません。" },
 */
export const NOTICES: readonly { date: string; body: string }[] = [];
